// 分聲(samson 範式):PHRASES=雲哲(男聲旁白/以利沙口吻)、SCRIPTURES=曉臻(柔和女聲唸和合本經文)。
// ⚠ edge-tts 雷:太短的句子與「,對不起」式結尾會斷流——句子保持完整、以驚嘆/句號收尾。
export function voiceKey(text) {
  const s = String(text).replace(/\s+/g, "");
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = (h * 0x01000193) >>> 0;
  }
  return h.toString(36);
}

